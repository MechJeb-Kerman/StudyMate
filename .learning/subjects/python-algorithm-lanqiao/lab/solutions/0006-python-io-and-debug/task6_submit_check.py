"""任务 6 · 提交前的两个搜索与一次逐字比对（参考解）

同一道题要跑两条路：自测在本机、提交在评测机。两条路的接口是同一个
—— 标准输入与标准输出。自测就是把样例存成文件、再接到标准输入上。

交出去之前做三件事：删掉调试用的 print；搜 input( 把括号里的参数删干净；
拿样例跑一遍、把标准输出与题面样例**逐字**对一遍。

same_output 就是第 3 件事的自动化。它的分寸在「放过什么、抓什么」上：

    放过  '78\n' 与 '78'    —— 文本文件末尾那一个换行是约定，不是差别
    抓    '78 \n' 与 '78\n' —— 行尾多一个空格（逐字比对要判错）
    抓    '78\n' 与 '78\n79\n' —— 少一行/多一行

所以别用 strip() 把两边空白都抹掉（那样前两条都会漏），
要按 splitlines() 切成行列表再比：行内的空格与行数都保留下来。
"""

import sys


# ── TODO 1 · 逐字比对 ────────────────────────────────────────────────────
def same_output(actual, expected):
    """逐字相同交回 True（判分接口，名字与参数别改）。"""
    return actual.splitlines() == expected.splitlines()


# ── TODO 2 · 提交前要搜的两个关键词 ──────────────────────────────────────
def search_terms():
    """交回两个字符串的列表（判分接口，名字别改）。"""
    return ['input(', 'print(']


# ── 给好的（别改）：自检的三个用例，判分会另加几组 ────────────────────────
print('01 完全相同', same_output('78\n', '78\n'))          # True
print('02 末尾换行', same_output('78\n', '78'))            # True
print('03 行尾多空格', same_output('78 \n', '78\n'))        # False
print('04 少一行', same_output('78\n', '78\n79\n'))        # False
print('05 搜两个关键词', search_terms())                    # ['input(', 'print(']
